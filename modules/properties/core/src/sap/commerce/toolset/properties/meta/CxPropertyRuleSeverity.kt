package sap.commerce.toolset.properties.meta

/** How loudly a [CxPropertyRule] is reported, and why the two tiers differ. */
enum class CxPropertyRuleSeverity(val title: String) {

    /** The declaration is actively harmful where it sits: it misleads, or it commits a secret. */
    ERROR("error"),

    /** The declaration is at best ignored and at worst breaks a build, but it harms nothing by being read. */
    WARNING("warning"),
}
